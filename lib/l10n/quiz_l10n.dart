/// Build a localized quiz bank from [QuizBanks] specs.
MissionQuizBank localizedQuizBank(AppLocalizations l10n, MissionId id) {
  return MissionQuizBank([
    for (final s in QuizBanks.forMission(id))
      QuizQuestion(
        prompt: quizL10nString(l10n, s.promptKey),
        options: [for (final k in s.optionKeys) quizL10nString(l10n, k)],
        correctIndex: s.correctIndex,
      ),
  ]);
}
